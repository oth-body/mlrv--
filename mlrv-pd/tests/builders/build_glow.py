p.connect(E1, 0, IH[2], 0)
p.connect(IH[2], 0, XM, 0)
p.connect(XM, 0, PKL, 0)
p.connect(PKL, 0, OUT_LED, 0)

# ---------------- ball physics (DONE_T out2) + ball write (out1) ----------------
