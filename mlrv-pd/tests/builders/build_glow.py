p.connect(PACKWB, 0, TABW_B, 0)
p.connect(CB2, 1, IH[5], 0)
p.connect(IH[5], 0, PK0, 1)
p.connect(CB2, 0, PK0, 0)
p.connect(PK0, 0, TABW_B, 0)
