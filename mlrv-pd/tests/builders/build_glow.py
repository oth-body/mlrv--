p.connect(SELC, 0, EMIT_T, 0)
p.connect(EMIT_T, 3, IH[4], 0)
p.connect(IH[4], 0, PKSH, 1)
p.connect(EMIT_T, 2, QH[1], 0)
p.connect(QH[1], 0, PKSH, 0)
p.connect(PKSH, 0, TABW_S, 0)
p.connect(EMIT_T, 1, QH[2], 0)
p.connect(QH[2], 0, PKL, 2)
p.connect(EMIT_T, 0, E1, 0)
p.connect(E1, 1, IH[3], 0)
