p.connect(MSG0, 0, QEXPR, 0)
p.connect(B2V, 1, QEXPR, 0)

# NOTE: IH[0] outlet -> TABR_B only; writeback staging uses IH[6]; clear
# index uses IH[5]. Every hold copy keeps exactly one outlet connection.

# ---------------- quantize / compare / emit ----------------
