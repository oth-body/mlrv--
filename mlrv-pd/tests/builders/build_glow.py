#!/usr/bin/env python3
"""Builder for mlrv-pd/patchers/glow.pd -- tilt-driven light toy for the
monome 64 (greyscale/varibright).

  serialosc.pd outlet 1 (keys) -> glow inlet 0
  serialosc.pd outlet 2 (tilt "sensor x y z") -> glow inlet 1
  glow outlet 0 (LED "x y level") -> grid.pd -> serialosc.pd LED inlet

Behavior: a bright comet drifts on tilt-vector input with friction and
wall bounce, over a phosphor layer that decays every tick (only cells
whose quantized level CHANGES emit LED traffic). Key press paints a
full-bright dot instantly. Shake (tilt magnitude spike) clears.
Direct messages: tilt <x> <y> <z>, clear, tick. Creation arg $1 = ms.

Wiring discipline (same as pong): a [float] outlet fans out ONLY to
silent store inlets; values read at N different times live in N
physical copies. The 64-cell loop reuses one fixed body; per-iteration
index travels via latched holds, never via stale fan-out.

Run from this directory:  python3 build_glow.py
"""
import sys
sys.path.insert(0, __file__.rsplit("/", 1)[0])
from pdgen import Patch

